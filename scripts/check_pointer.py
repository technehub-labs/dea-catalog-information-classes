#!/usr/bin/env python3
"""Gate 2: metamodel-pointer.yaml is present and internally consistent.

The pointer is regenerated by the OpenDEAM root-model fan-out and is never
hand-edited. This gate does not rewrite it: it asserts that the pointer
declares the fields the allocation validator and the human reader both rely
on, and that the identity values match what docs/FOUNDATIONS.md section 5
records as the allocation.

A finding here means the pointer drifted from its allocation. Fix the
allocation in dea-architecture-framework, not this file.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent

# The OpenDEAM v0.2.1 fan-out does not emit a metamodel.status field;
# catalog.status carries the lifecycle state. Newer fan-outs (v0.7.0)
# add metamodel.status; this gate asserts the v0.2.1 shape.
REQUIRED_METAMODEL_FIELDS = (
    "version",
    "entity_id",
    "class_alias",
    "layer",
    "building_block",
    "viewer_url",
)
REQUIRED_CATALOG_FIELDS = ("name", "repo", "status")

EXPECTED_CLASS_ALIAS = "IC"
EXPECTED_ENTITY_ID = "dea:entity-information-class"
EXPECTED_REPO = "technehub-labs/dea-catalog-information-classes"
EXPECTED_LAYER = "L4"
EXPECTED_BUILDING_BLOCK = "L4-data-foundation"


def main() -> int:
    findings: list[str] = []

    path = REPO / "metamodel-pointer.yaml"
    if not path.exists():
        print("FAIL: metamodel-pointer.yaml is missing")
        print(f"Findings: 1")
        return 1

    doc = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    metamodel = doc.get("metamodel") or {}
    catalog = doc.get("catalog") or {}

    for field in REQUIRED_METAMODEL_FIELDS:
        if not str(metamodel.get(field, "")).strip():
            findings.append(f"metamodel.{field} is missing or empty")

    for field in REQUIRED_CATALOG_FIELDS:
        if not str(catalog.get(field, "")).strip():
            findings.append(f"catalog.{field} is missing or empty")

    if metamodel.get("class_alias") != EXPECTED_CLASS_ALIAS:
        findings.append(f"metamodel.class_alias is {metamodel.get('class_alias')!r}, expected {EXPECTED_CLASS_ALIAS!r}")
    if metamodel.get("entity_id") != EXPECTED_ENTITY_ID:
        findings.append(f"metamodel.entity_id is {metamodel.get('entity_id')!r}, expected {EXPECTED_ENTITY_ID!r}")
    if metamodel.get("layer") != EXPECTED_LAYER:
        findings.append(f"metamodel.layer is {metamodel.get('layer')!r}, expected {EXPECTED_LAYER!r}")
    if metamodel.get("building_block") != EXPECTED_BUILDING_BLOCK:
        findings.append(
            f"metamodel.building_block is {metamodel.get('building_block')!r}, expected {EXPECTED_BUILDING_BLOCK!r}"
        )
    if catalog.get("repo") != EXPECTED_REPO:
        findings.append(f"catalog.repo is {catalog.get('repo')!r}, expected {EXPECTED_REPO!r}")

    if findings:
        print("Pointer findings:")
        for f in findings:
            print(f"  - FAIL: {f}")
    else:
        print(f"  OK: metamodel-pointer.yaml internally consistent ({metamodel.get('version')})")
    print(f"Findings: {len(findings)}")
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main())
